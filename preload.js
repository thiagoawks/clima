const { contextBridge, ipcRenderer } = require('electron');

const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);
const on = (channel, fn) => ipcRenderer.on(channel, (_e, ...args) => fn(...args));

contextBridge.exposeInMainWorld('api', {
  getSettings: () => call('settings:get'),
  setSettings: patch => call('settings:set', patch),
  setToken: t => call('token:set', t),
  pasteToken: () => call('token:paste'),
  clearAuth: () => call('auth:clear'),
  oauthStart: opts => call('oauth:start', opts),
  updateGet: () => call('update:get'),
  updateCheck: () => call('update:check'),
  updateInstall: () => call('update:install'),
  openExternal: u => call('open:external', u),
  load: () => call('data:load'),
  cached: () => call('data:cached'),
  command: c => call('device:command', c),
  setTimer: (id, minutes) => call('timer:set', { id, minutes }),
  setSchedules: list => call('schedules:set', list),
  setScenes: list => call('scenes:set', list),
  runScene: id => call('scene:run', id),
  night: id => call('night:run', id),
  washDismiss: id => call('wash:dismiss', id),
  setAuto: (id, v) => call('auto:set', { id, on: v }),
  exportEnergy: () => call('energy:export'),
  copyDiag: () => call('diag:copy'),
  newsSeen: () => call('news:seen'),
  setMini: v => call('mini:set', v),
  showMain: () => call('win:show'),
  minimize: () => call('win:minimize'),
  maximize: () => call('win:maximize'),
  close: () => call('win:close'),
  onRefresh: fn => on('refresh', fn),
  onData: fn => on('data', fn),
  onSettings: fn => on('settings', fn),
  onMaximized: fn => on('maximized', fn),
  onVisible: fn => on('visible', fn),
  onUpdate: fn => on('update', fn),
});
