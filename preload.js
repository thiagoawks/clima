const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: patch => ipcRenderer.invoke('settings:set', patch),
  setToken: t => ipcRenderer.invoke('token:set', t),
  clearAuth: () => ipcRenderer.invoke('auth:clear'),
  oauthAutoSetup: opts => ipcRenderer.invoke('oauth:autosetup', opts),
  updateGet: () => ipcRenderer.invoke('update:get'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  onUpdate: fn => ipcRenderer.on('update', (_e, u) => fn(u)),
  oauthStart: opts => ipcRenderer.invoke('oauth:start', opts),
  openExternal: u => ipcRenderer.invoke('open:external', u),
  load: () => ipcRenderer.invoke('data:load'),
  cached: () => ipcRenderer.invoke('data:cached'),
  command: c => ipcRenderer.invoke('device:command', c),
  setTimer: (id, minutes) => ipcRenderer.invoke('timer:set', { id, minutes }),
  setSchedules: list => ipcRenderer.invoke('schedules:set', list),
  setAuto: (id, on) => ipcRenderer.invoke('auto:set', { id, on }),
  setMini: on => ipcRenderer.invoke('mini:set', on),
  showMain: () => ipcRenderer.invoke('win:show'),
  minimize: () => ipcRenderer.invoke('win:minimize'),
  maximize: () => ipcRenderer.invoke('win:maximize'),
  close: () => ipcRenderer.invoke('win:close'),
  onRefresh: fn => ipcRenderer.on('refresh', () => fn()),
  onData: fn => ipcRenderer.on('data', (_e, d) => fn(d)),
  onSettings: fn => ipcRenderer.on('settings', () => fn()),
  onMaximized: fn => ipcRenderer.on('maximized', (_e, v) => fn(v)),
});
